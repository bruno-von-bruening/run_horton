def process_mp2_file_core(lines, expected_keys):
    """ Get lines and return new lines"""
    def manipulate_mp2_file(lines, found):
        """ 
        Create copy of the file
        Delete the MP2 density block
        """
        scf_tag='scf'

        scf_pair=found[scf_tag]
        rpl_tag=[ x for x in found.keys() if x!=scf_tag]
        assert len(rpl_tag)==1
        rpl_tag=rpl_tag[0]
        rpl_pair=found[rpl_tag]

        # Make sure lines are numbered
        if isinstance(lines[0],str):
            new_lines=[ (i,l) for i,l in enumerate(lines)]
        else:
            new_lines=copy.deepcopy(lines)
        

        # Change the title of the MP2 block
        rpl_line_num=rpl_pair[0]
        # find the right number
        rpl_line_num=[ i for i,(num,l) in enumerate(new_lines) if num==rpl_line_num]
        assert len(rpl_line_num)==1, rpl_line_num
        rpl_line_num=rpl_line_num[0]
        # Replace the section
        new_lines[rpl_line_num]=(rpl_line_num, new_lines[rpl_line_num][1].replace(rpl_tag.upper(),scf_tag.upper()))

        # remove the SCF block
        scf_line_num=found[scf_tag][0]
        low,up=title_line_ranges[scf_line_num]
        new_lines=[ (i,l) for i,l in new_lines if i <low or i>=up]

        new_lines=[x[1] for x  in new_lines]
        return new_lines
    def search_lines(lines, search_string):
        if isinstance(lines[0], str):
            lines=[(i,l) for i,l in enumerate(lines)]
        found_lines=[ (i,x) for i,x in lines if re.match(search_string, x)]
        return found_lines

    # Get all lines that do not start with an space (these are the title lines)
    search_string=r'^[^/ ]'
    title_lines=search_lines(lines, search_string)

    # Get all the sections
    title_line_ranges={}
    for index, (num, line) in enumerate(title_lines):
        lower=num
        if index+1<len(title_lines):
            next=title_lines[index+1]
            upper=title_lines[index+1][0]
        else:
            upper=len(lines)
        title_line_ranges.update({num:(lower,upper)})

    # Get the density lines
    search_string=r'^Total [^\ ]* Density'
    density_lines=search_lines(title_lines, search_string)

    # Check the density lines
    if len(density_lines)==0:
        raise Exception(f"Could not find line that matches {search_string}")
    elif len(density_lines)==1:
        # Only scf density -> nothing to do
        assert density_lines[0][1].startswith(expected_keys['scf']), f"Expected line starting with \'{expected_keys['mp2']}\', found \'{density_lines[0][1]}\'"
        return lines
    elif len(density_lines)==2:
        counts={}
        found={}
        for k,search in expected_keys.items():
            counts.update({k: len([ x for i,x in density_lines if x.startswith(search)])})
        assert counts['scf']==1 and ( sum([counts[x] for x in expected_keys.keys() if x!='scf' ])==1 )
        for k,search in expected_keys.items():
            if counts[k]>0:
                found.update({k: [ x for x in density_lines if x[1].startswith(search)][0]})

        
        new_lines=manipulate_mp2_file(lines, found)
        return new_lines
    else:
        raise Exception()

